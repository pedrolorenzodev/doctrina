import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const catalogue = JSON.parse(readFileSync(join(root, "assets/icons/icons.json"), "utf8"));
const excluded = new Set(["app-icon"]);

const first = (icon, field) => icon.occurrences.map((occurrence) => occurrence[field]).find((value) => value);

function shapeOf(element) {
  const { tag, linecap, ...attributes } = element;
  const shape = { tag, ...attributes };
  if (linecap) shape.linecap = linecap;
  return shape;
}

const entries = catalogue.icons
  .filter((icon) => !excluded.has(icon.name))
  .map((icon) => {
    const spec = { viewBox: icon.viewBox, mode: icon.mode };
    if (icon.mode === "stroke") {
      spec.strokeWidth = icon.strokeWidthsUsed[0];
      const linecap = first(icon, "linecap");
      const linejoin = first(icon, "linejoin");
      if (linecap) spec.linecap = linecap;
      if (linejoin) spec.linejoin = linejoin;
    }
    spec.shapes = icon.elements.map(shapeOf);
    return [icon.name, spec];
  });

const body = entries.map(([name, spec]) => `  ${JSON.stringify(name)}: ${JSON.stringify(spec)},`).join("\n");
let output = [
  "// guard: generated by apps/mobile/scripts/build-icons.mjs from assets/icons/icons.json; edit the catalogue and rerun it",
  'import type { IconSpec } from "@/components/icons/icon-spec";',
  "",
  `export const iconShapes = {\n${body}\n} as const satisfies Record<string, IconSpec>;`,
  "",
  "export type IconName = keyof typeof iconShapes;",
  "",
].join("\n");

const prettier = join(root, "../../node_modules/.bin/prettier");
output = execFileSync(prettier, ["--stdin-filepath", "icon-shapes.ts"], { input: output, cwd: root }).toString();
writeFileSync(join(root, "src/components/icons/icon-shapes.ts"), output);
console.log(`${entries.length} icons written`);
